// Stacks are data structures that follows LIFO(Last In First Out) Principle.
// In stacks elements can be added and remvoed only at the top nor in between neither in end.

// Functions of the stack:-

// Push :- For inserting a element in the stack(on the top).
// Pop :- For removing a element from the stack(from the top).
// isEmpty :- To check if the stack is empty or not.
// isFull :- To check whether the stack is full or not.
// size :- For getting the size of the stack.
// Top :- To check the top most element of the stack.

// Overflow :- Adding elements after exceding the size of of stack is defined as Overflow.
// Underflow :- Removing the elements from the empty stack is called Underflow.
