// STL(Standrd Template Library):-
// Set of template classes for implementing commonly used data structures & functions.
// For eg: vector<int>, vector<char>

// 3 major components of STL:-
// a. Containers
// b. Iterators
// c. Algorithms

// Containers:- Used to hold data of same type.
// For eg:-
// i. vector:- Classes that defines the dynamic array.
// ii. list:- Class for doubly linked list.
// iii. map:- Used to store unqiue key value pairs.
// iv. set:- Used to store unique values.

// Iterators:- These are pointer like entities that are used to iterate/traverse the container.
// For eg:- Defining a vector:- vector<int> v = {1,2,3,4,5};
//          Defining a iterator to traverse this vector(container): vector<int> :: iterator itr;
//          itr.begin() = 1 (First Element of the container will be fetched using this function)

// Algorithms:- Functions that are used to manipulate data in the containers.
// For eg:- sort(v.begin(), v.end()), min(a,b), max(a,b)

